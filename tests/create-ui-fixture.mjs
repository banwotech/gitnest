import { mkdtemp, mkdir, realpath, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { tmpdir } from 'node:os';

const root = await realpath(await mkdtemp(path.join(tmpdir(), 'gitnest-actions-ui-')));
const workspace = path.join(root, 'GitNest-操作验证');
const frontend = path.join(workspace, 'frontend');
const remote = path.join(root, 'remote.git');
const peer = path.join(root, 'peer');
const userData = path.join(root, 'settings');
await mkdir(path.join(frontend, 'src'), { recursive: true });
await mkdir(remote);
const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
git(remote, 'init', '--bare');
git(frontend, 'init', '-b', 'feature/workspace');
git(frontend, 'config', 'user.name', 'GitNest UI Test');
git(frontend, 'config', 'user.email', 'ui-test@gitnest.local');
git(frontend, 'config', 'commit.gpgsign', 'false');
const original = '<?php\n\nfunction app_version() {\n    return "version-1";\n}\n\nfunction status() {\n    return "ok";\n}\n';
await writeFile(path.join(frontend, 'src', 'app.php'), original);
await writeFile(path.join(frontend, 'README.md'), '# Original project\n');
git(frontend, 'add', '.');
git(frontend, 'commit', '-m', 'Initial fixture');
git(frontend, 'remote', 'add', 'origin', remote);
git(frontend, 'push', '-u', 'origin', 'HEAD:refs/heads/feature/workspace');
git(root, 'clone', '--branch', 'feature/workspace', remote, peer);
git(peer, 'config', 'user.name', 'GitNest Remote Test');
git(peer, 'config', 'user.email', 'remote-test@gitnest.local');
git(peer, 'config', 'commit.gpgsign', 'false');
await writeFile(path.join(frontend, 'src', 'app.php'), original.replace('version-1', 'version-2-staged'));
git(frontend, 'add', 'src/app.php');
await writeFile(path.join(frontend, 'src', 'app.php'), original.replace('version-1', 'version-3-working'));
await writeFile(path.join(frontend, 'README.md'), '# Working README\n');
await writeFile(path.join(frontend, 'notes.txt'), 'Keep this untracked file on disk.\n');
process.stdout.write(JSON.stringify({ root, workspace, frontend, remote, peer, userData }));
