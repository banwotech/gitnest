test('unstaging a rename or deletion restores only the index and never the worktree', async (t) => {
  const { root, frontend } = await fixture(t);
  await writeFile(path.join(frontend, 'old name.php'), '<?php\necho "first";\necho "last";\n');
  await writeFile(path.join(frontend, 'deleted.txt'), 'original\n');
  commit(frontend);
  git(frontend, 'mv', 'old name.php', 'new name.php');
  await unlink(path.join(frontend, 'deleted.txt'));
  const repository = { path: frontend };
  await performRepositoryAction(repository, 'stage', { paths: ['deleted.txt'] });
  const current = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  const rename = current.files.find((item) => item.kind === 'renamed');
  const stagedRename = await readComparison(current, rename, 'staged');
  assert.equal(stagedRename.original, stagedRename.modified);
  const stagedDelete = await readComparison(current, current.files.find((item) => item.path === 'deleted.txt'), 'staged');
  assert.equal(stagedDelete.modified, '');
  await performRepositoryAction(repository, 'unstage', { paths: ['new name.php'] });
  assert.equal(git(frontend, 'ls-files', '--', 'new name.php'), '');
  assert.equal(git(frontend, 'ls-files', '--', 'old name.php'), 'old name.php');
  assert.equal(await readFile(path.join(frontend, 'new name.php'), 'utf8'), '<?php\necho "first";\necho "last";\n');
  await assert.rejects(() => readFile(path.join(frontend, 'old name.php')), { code: 'ENOENT' });
  await performRepositoryAction(repository, 'unstage', { paths: ['deleted.txt'] });
  await assert.rejects(() => readFile(path.join(frontend, 'deleted.txt')), { code: 'ENOENT' });
  assert.equal(git(frontend, 'show', ':deleted.txt'), 'original');
});

