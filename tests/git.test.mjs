test('staging and committing use only index content, preserving later edits and other files', async (t) => {
  const { root, frontend } = await fixture(t);
  await writeFile(path.join(frontend, 'app.php'), '<?php echo "first";\n');
  await writeFile(path.join(frontend, 'other.txt'), 'first\n');
  commit(frontend);
  const repository = { path: frontend };
  await writeFile(path.join(frontend, 'app.php'), '<?php echo "staged";\n');
  await writeFile(path.join(frontend, 'other.txt'), 'not staged\n');
  await performRepositoryAction(repository, 'stage', { paths: ['app.php'] });
  await writeFile(path.join(frontend, 'app.php'), '<?php echo "latest disk";\n');
  let current = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  const file = current.files.find((item) => item.path === 'app.php');
  assert.equal(file.staged, true);
  assert.equal(file.unstaged, true);
  const staged = await readComparison(current, file, 'staged');
  const working = await readComparison(current, file);
  assert.equal(staged.original, '<?php echo "first";\n');
  assert.equal(staged.modified, '<?php echo "staged";\n');
  assert.equal(working.modified, '<?php echo "latest disk";\n');
  assert.equal(staged.source, 'staged');
  await performRepositoryAction(repository, 'commit', { message: '只提交暂存区\n\nliteral $(printf never-run) `echo also-literal`' });
  assert.equal(git(frontend, 'show', 'HEAD:app.php'), '<?php echo "staged";');
  assert.equal(git(frontend, 'show', 'HEAD:other.txt'), 'first');
  assert.equal(await readFile(path.join(frontend, 'app.php'), 'utf8'), '<?php echo "latest disk";\n');
  assert.match(git(frontend, 'log', '-1', '--format=%B'), /\$\(printf never-run\)/);
  current = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  assert.equal(current.files.length, 2);
  assert.equal(current.files.filter((item) => item.staged).length, 0);
  await assert.rejects(() => performRepositoryAction(repository, 'commit', { message: 'no staged changes' }), /先暂存/);
  await assert.rejects(() => performRepositoryAction(repository, 'stage', { paths: ['../outside'] }), /状态已变化/);
});

