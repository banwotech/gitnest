test('preserves full unchanged context and reads symlink targets without following them', async (t) => {
  const { root, frontend } = await fixture(t);
  const original = Array.from({ length: 150 }, (_, index) => `line ${index + 1}`).join('\n') + '\n';
  await writeFile(path.join(frontend, 'long.txt'), original);
  await symlink('/tmp/old-target', path.join(frontend, 'link'));
  commit(frontend);
  await writeFile(path.join(frontend, 'long.txt'), original.replace('line 75\n', 'line 75 changed\n'));
  await unlink(path.join(frontend, 'link'));
  await symlink('/tmp/new-target', path.join(frontend, 'link'));
  const project = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  const content = await readComparison(project, project.files.find((item) => item.path === 'long.txt'));
  assert.equal(content.original.split('\n').length, 151);
  assert.equal(content.modified.split('\n').length, 151);
  assert.match(content.original, /line 1\n/);
  assert.match(content.modified, /line 150\n$/);
  const link = await readComparison(project, project.files.find((item) => item.path === 'link'));
  assert.equal(link.original, '/tmp/old-target');
  assert.equal(link.modified, '/tmp/new-target');
  await assert.rejects(() => readComparison(project, { path: '../outside' }), /无效/);
  assert.equal(await readFile(path.join(frontend, 'long.txt'), 'utf8'), content.modified);
});

test('reports actual merge conflicts and does not alter the index', async (t) => {
  const { root, frontend } = await fixture(t);
  await writeFile(path.join(frontend, 'conflict.txt'), 'base\n');
  commit(frontend);
  git(frontend, 'checkout', '-b', 'other');
  await writeFile(path.join(frontend, 'conflict.txt'), 'other\n');
  commit(frontend);
  git(frontend, 'checkout', 'feature/workspace');
  await writeFile(path.join(frontend, 'conflict.txt'), 'ours\n');
  commit(frontend);
  try { git(frontend, 'merge', 'other'); } catch {}
  const before = git(frontend, 'ls-files', '--stage');
  const project = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  assert.equal(project.files[0].kind, 'conflict');
  const comparison = await readComparison(project, project.files[0]);
  assert.equal(comparison.original, 'ours\n');
  assert.match(comparison.modified, /<<<<<<< HEAD/);
  await assert.rejects(performRepositoryAction({ path: frontend }, 'switch', { branch: 'refs/heads/other' }), /合并冲突/);
  assert.equal(git(frontend, 'ls-files', '--stage'), before);
  const unmergedBefore = git(frontend, 'ls-files', '--unmerged');
  await writeFile(path.join(frontend, 'independent.txt'), 'separately staged\n');
  await performRepositoryAction({ path: frontend }, 'stage', { paths: ['independent.txt'] });
  await performRepositoryAction({ path: frontend }, 'unstage');
  assert.equal(git(frontend, 'ls-files', '--unmerged'), unmergedBefore);
  assert.equal(await readFile(path.join(frontend, 'independent.txt'), 'utf8'), 'separately staged\n');
});

