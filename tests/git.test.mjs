test('push sets upstream and targets only the selected branch, pull fast-forwards and refuses divergence', async (t) => {
  const { root, frontend } = await fixture(t);
  const remote = path.join(root, 'remote.git');
  await mkdir(remote);
  git(remote, 'init', '--bare');
  await writeFile(path.join(frontend, 'app.txt'), 'first\n');
  commit(frontend);
  git(frontend, 'remote', 'add', 'origin', remote);
  const repository = { path: frontend };
  await performRepositoryAction(repository, 'push', { remote: 'origin' });
  let current = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  assert.equal(current.upstreamRemote, 'origin');
  assert.equal(current.upstreamBranch, 'refs/heads/feature/workspace');
  assert.deepEqual(current.remotes, ['origin']);
  const initialHead = git(frontend, 'rev-parse', 'HEAD');
  git(frontend, 'branch', 'other');
  git(frontend, 'push', 'origin', 'other:refs/heads/other');
  git(frontend, 'checkout', 'other');
  await writeFile(path.join(frontend, 'other.txt'), 'only local other branch\n');
  commit(frontend);
  git(frontend, 'checkout', 'feature/workspace');
  git(frontend, 'config', 'push.default', 'matching');
  await writeFile(path.join(frontend, 'app.txt'), 'second\n');
  commit(frontend);
  await performRepositoryAction(repository, 'push', { remote: 'origin' });
  assert.equal(git(remote, 'rev-parse', 'refs/heads/feature/workspace'), git(frontend, 'rev-parse', 'HEAD'));
  assert.equal(git(remote, 'rev-parse', 'refs/heads/other'), initialHead);
  const peer = path.join(root, 'peer');
  git(root, 'clone', '--branch', 'feature/workspace', remote, peer);
  git(peer, 'config', 'user.name', 'GitNest Peer');
  git(peer, 'config', 'user.email', 'peer@gitnest.local');
  await writeFile(path.join(peer, 'app.txt'), 'third from remote\n');
  commit(peer);
  git(peer, 'push', 'origin', 'HEAD:refs/heads/feature/workspace');
  await performRepositoryAction(repository, 'pull', { remote: 'origin' });
  assert.equal(await readFile(path.join(frontend, 'app.txt'), 'utf8'), 'third from remote\n');
  await writeFile(path.join(frontend, 'local.txt'), 'local divergent commit\n');
  commit(frontend);
  await writeFile(path.join(peer, 'remote.txt'), 'remote divergent commit\n');
  commit(peer);
  git(peer, 'push', 'origin', 'HEAD:refs/heads/feature/workspace');
  const beforePull = git(frontend, 'rev-parse', 'HEAD');
  await assert.rejects(() => performRepositoryAction(repository, 'pull', { remote: 'origin' }));
  assert.equal(git(frontend, 'rev-parse', 'HEAD'), beforePull);
  await assert.rejects(() => performRepositoryAction(repository, 'push', { remote: 'origin' }));
  assert.equal(git(remote, 'rev-parse', 'refs/heads/feature/workspace'), git(peer, 'rev-parse', 'HEAD'));
  await assert.rejects(() => performRepositoryAction(repository, 'push', { remote: 'unknown' }), /已配置/);
  git(frontend, 'checkout', '--detach');
  await assert.rejects(() => performRepositoryAction(repository, 'push', { remote: 'origin' }), /游离 HEAD/);
});

test('branch switching updates HEAD while preserving compatible staged, working and untracked changes', async (t) => {
  const { root, frontend } = await fixture(t);
  await writeFile(path.join(frontend, 'app.txt'), 'original\n');
  commit(frontend);
  git(frontend, 'switch', '-c', 'feature/target');
  await writeFile(path.join(frontend, 'target.txt'), 'target branch\n');
  commit(frontend);
  const targetHead = git(frontend, 'rev-parse', 'HEAD');
  git(frontend, 'switch', 'feature/workspace');
  await writeFile(path.join(frontend, 'app.txt'), 'staged\n');
  git(frontend, 'add', 'app.txt');
  await writeFile(path.join(frontend, 'app.txt'), 'working\n');
  await writeFile(path.join(frontend, 'untracked.txt'), 'untracked\n');
  await performRepositoryAction({ path: frontend }, 'switch', { branch: 'refs/heads/feature/target' });
  const project = (await scanWorkspace(root)).projects.find((item) => item.path === frontend);
  assert.equal(project.branchName, 'feature/target');
  assert.equal(project.head, targetHead);
  assert.ok(project.branches.some((branch) => branch.ref === 'refs/heads/feature/workspace' && !branch.remote));
  assert.equal(git(frontend, 'show', ':app.txt'), 'staged');
  assert.equal(await readFile(path.join(frontend, 'app.txt'), 'utf8'), 'working\n');
  assert.equal(await readFile(path.join(frontend, 'untracked.txt'), 'utf8'), 'untracked\n');
  assert.ok(project.files.find((file) => file.path === 'app.txt').staged);
  assert.ok(project.files.find((file) => file.path === 'app.txt').unstaged);
  assert.equal(git(frontend, 'stash', 'list'), '');
});

test('branch switching refuses to overwrite local or untracked files and rejects unknown refs', async (t) => {
  const { frontend } = await fixture(t);
  await writeFile(path.join(frontend, 'app.txt'), 'original\n');
  commit(frontend);
  git(frontend, 'switch', '-c', 'other');
  await writeFile(path.join(frontend, 'app.txt'), 'other branch\n');
  await writeFile(path.join(frontend, 'new.txt'), 'tracked in other\n');
  commit(frontend);
  git(frontend, 'switch', 'feature/workspace');
  const head = git(frontend, 'rev-parse', 'HEAD');
  await writeFile(path.join(frontend, 'app.txt'), 'my staged edit\n');
  git(frontend, 'add', 'app.txt');
  await assert.rejects(performRepositoryAction({ path: frontend }, 'switch', { branch: 'refs/heads/other' }));
  assert.equal(git(frontend, 'rev-parse', 'HEAD'), head);
  assert.equal(git(frontend, 'show', ':app.txt'), 'my staged edit');
  assert.equal(await readFile(path.join(frontend, 'app.txt'), 'utf8'), 'my staged edit\n');
  git(frontend, 'restore', '--staged', 'app.txt');
  await writeFile(path.join(frontend, 'app.txt'), 'original\n');
  await writeFile(path.join(frontend, 'new.txt'), 'my untracked file\n');
  await assert.rejects(performRepositoryAction({ path: frontend }, 'switch', { branch: 'refs/heads/other' }));
  assert.equal(await readFile(path.join(frontend, 'new.txt'), 'utf8'), 'my untracked file\n');
  for (const branch of ['--discard-changes', 'refs/heads/missing', 'refs/tags/other']) await assert.rejects(performRepositoryAction({ path: frontend }, 'switch', { branch }), /目标分支/);
  assert.equal(git(frontend, 'branch', '--show-current'), 'feature/workspace');
  assert.equal(git(frontend, 'stash', 'list'), '');
});

