test('commit picker supports branches, literal search and pagination without changing repository state', async (t) => {
  const { frontend, backend } = await fixture(t);
  assert.deepEqual(await readCommits({ path: backend }), { commits: [], hasMore: false });
  await writeFile(path.join(frontend, 'app.txt'), 'original\n');
  commit(frontend);
  const base = git(frontend, 'rev-parse', 'HEAD');
  git(frontend, 'branch', 'base');
  for (let index = 0; index < 53; index++) git(frontend, 'commit', '--allow-empty', '-m', `History ${index}${index === 12 ? ' literal[needle]' : ''}`);
  const head = git(frontend, 'rev-parse', 'HEAD');
  const first = await readCommits({ path: frontend });
  const second = await readCommits({ path: frontend }, { offset: 50 });
  assert.equal(first.commits.length, 50);
  assert.equal(first.hasMore, true);
  assert.equal(second.commits.length, 4);
  assert.equal(second.hasMore, false);
  assert.equal(new Set([...first.commits, ...second.commits].map((item) => item.id)).size, 54);
  assert.equal(first.commits[0].id, head);
  const filtered = await readCommits({ path: frontend }, { query: 'LITERAL[needle]' });
  assert.equal(filtered.commits.length, 1);
  assert.equal(filtered.commits[0].subject, 'History 12 literal[needle]');
  assert.equal(filtered.commits[0].author, 'GitNest Test');
  assert.match(filtered.commits[0].date, /^\d{4}-/);
  const branch = await readCommits({ path: frontend }, { ref: 'refs/heads/base' });
  assert.equal(branch.commits.length, 1);
  assert.equal(branch.commits[0].id, base);
  assert.match(branch.commits[0].refs, /base/);
  for (const options of [{ ref: '--all' }, { offset: -1 }, { query: 'x'.repeat(301) }]) await assert.rejects(readCommits({ path: frontend }, options));
  assert.equal(git(frontend, 'rev-parse', 'HEAD'), head);
  assert.equal(git(frontend, 'status', '--porcelain'), '');
});

