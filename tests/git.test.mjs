import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm, symlink, unlink, realpath, chmod } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { scanWorkspace, readComparison, readCommits, performRepositoryAction } from '../electron/git.mjs';

const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();

async function fixture(t) {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), 'gitnest-test-')));
  t.after(() => rm(root, { recursive: true, force: true }));
  const frontend = path.join(root, 'frontend');
  const backend = path.join(root, 'backend');
  for (const directory of [frontend, backend]) {
    await mkdir(directory);
    git(directory, 'init', '-b', directory === frontend ? 'feature/workspace' : 'main');
    git(directory, 'config', 'user.name', 'GitNest Test');
    git(directory, 'config', 'user.email', 'test@gitnest.local');
  }
  await mkdir(path.join(root, 'design'));
  return { root, frontend, backend };
}

const commit = (directory) => { git(directory, 'add', '.'); git(directory, 'commit', '-m', 'Initial project'); };

test('opens a non-Git parent and reports immediate child branches and unique file counts', async (t) => {
  const { root, frontend, backend } = await fixture(t);
  await writeFile(path.join(frontend, 'app.ts'), 'const version = 1;\n');
  commit(frontend);
  await writeFile(path.join(frontend, 'app.ts'), 'const version = 2;\n');
  git(frontend, 'add', 'app.ts');
  await writeFile(path.join(frontend, 'app.ts'), 'const version = 3;\n');
  await mkdir(path.join(frontend, 'src'));
  await writeFile(path.join(frontend, 'src', '新 文件.ts'), 'export const hello = true;\n');
  const workspace = await scanWorkspace(root);
  const front = workspace.projects.find((item) => item.path === frontend);
  assert.equal(front.branch, 'feature/workspace');
  assert.equal(front.files.length, 2);
  assert.equal(front.files.find((file) => file.path === 'app.ts').staged, true);
  assert.equal(front.files.find((file) => file.path === 'app.ts').unstaged, true);
  assert.equal(workspace.projects.find((item) => item.path === backend).head, null);
  assert.equal(workspace.projects.find((item) => item.name === 'design').isRepository, false);
  assert.equal(workspace.projects.length, 3);
  const comparison = await readComparison(front, front.files.find((file) => file.path === 'app.ts'));
  assert.equal(comparison.original, 'const version = 1;\n');
  assert.equal(comparison.modified, 'const version = 3;\n');
  const untracked = await readComparison(front, front.files.find((file) => file.path.includes('新 文件')));
  assert.equal(untracked.original, '');
  assert.equal(untracked.modified, 'export const hello = true;\n');
});

test('compares renamed, deleted, binary and unborn files correctly', async (t) => {
  const { root, frontend, backend } = await fixture(t);
  await writeFile(path.join(frontend, 'old name.ts'), 'export const value = 1;\n');
  await writeFile(path.join(frontend, 'deleted.ts'), 'deleted content\n');
  await writeFile(path.join(frontend, 'binary.bin'), Buffer.from([0, 1, 2]));
  commit(frontend);
  git(frontend, 'mv', 'old name.ts', 'new 文件.ts');
  await writeFile(path.join(frontend, 'new 文件.ts'), 'export const value = 2;\n');
  await unlink(path.join(frontend, 'deleted.ts'));
  await writeFile(path.join(frontend, 'binary.bin'), Buffer.from([0, 3, 4]));
  await writeFile(path.join(backend, 'first.ts'), 'first file\n');
  const workspace = await scanWorkspace(root);
  const front = workspace.projects.find((item) => item.path === frontend);
  const renamed = front.files.find((file) => file.kind === 'renamed');
  assert.equal(renamed.path, 'new 文件.ts');
  assert.equal(renamed.originalPath, 'old name.ts');
  const comparison = await readComparison(front, renamed);
  assert.equal(comparison.original, 'export const value = 1;\n');
  assert.equal(comparison.modified, 'export const value = 2;\n');
  const deleted = await readComparison(front, front.files.find((file) => file.kind === 'deleted'));
  assert.equal(deleted.original, 'deleted content\n');
  assert.equal(deleted.modified, '');
  assert.equal((await readComparison(front, front.files.find((file) => file.path === 'binary.bin'))).kind, 'binary');
  const back = workspace.projects.find((item) => item.path === backend);
  const unborn = await readComparison(back, back.files[0]);
  assert.equal(unborn.original, '');
  assert.equal(unborn.modified, 'first file\n');
});

